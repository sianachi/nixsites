/**
 * Builds src/generated/operations.ts from Core's committed OpenAPI contract: one compact entry per
 * `/api/v1` operation, which the generic "find an action / run an action" tools of the pet, MCP and
 * the CLI read. Run through `pnpm --filter @nix/api-client generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';

type Json = Record<string, unknown>;

const contract = JSON.parse(
  readFileSync(new URL('../../../backend/openapi/nix-api.json', import.meta.url), 'utf8'),
) as { paths: Record<string, Record<string, Json>>; components: { schemas: Record<string, Json> } };

const MAX_DEPTH = 4;

/** The parts of a JSON schema a model needs to build a request body; `$ref`s resolved. */
function compact(schema: Json | undefined, depth = 0): Json | undefined {
  if (schema === undefined) return undefined;
  const ref = schema.$ref;
  if (typeof ref === 'string') {
    if (depth >= MAX_DEPTH) return { type: 'object' };
    return compact(
      contract.components.schemas[ref.replace('#/components/schemas/', '')],
      depth + 1,
    );
  }
  const out: Json = {};
  if (schema.type !== undefined) out.type = schema.type;
  if (Array.isArray(schema.enum)) out.enum = schema.enum;
  if (typeof schema.format === 'string' && ['uuid', 'date', 'date-time'].includes(schema.format))
    out.format = schema.format;
  if (typeof schema.maxLength === 'number') out.maxLength = schema.maxLength;
  if (Array.isArray(schema.required) && schema.required.length > 0) out.required = schema.required;
  if (schema.items !== undefined) out.items = compact(schema.items as Json, depth + 1);
  for (const key of ['oneOf', 'anyOf'] as const) {
    if (Array.isArray(schema[key]))
      out[key] = (schema[key] as Json[]).map((entry) => compact(entry, depth + 1));
  }
  if (schema.properties !== undefined && depth < MAX_DEPTH) {
    out.properties = Object.fromEntries(
      Object.entries(schema.properties as Record<string, Json>).map(([name, value]) => [
        name,
        compact(value, depth + 1),
      ]),
    );
  }
  return out;
}

/** The description's first sentence, so a match explains itself without the whole paragraph. */
function firstSentence(text: unknown): string {
  if (typeof text !== 'string') return '';
  const sentence = text.split(/(?<=\.)\s/)[0] ?? '';
  return sentence.length <= 240 ? sentence : `${sentence.slice(0, 237)}...`;
}

const entries: Json[] = [];
for (const [path, methods] of Object.entries(contract.paths)) {
  if (!path.startsWith('/api/v1/')) continue;
  for (const [method, operation] of Object.entries(methods)) {
    if (typeof operation.operationId !== 'string') continue;
    const parameters = (operation.parameters ?? []) as Json[];
    const body = (operation.requestBody as Json | undefined)?.content as
      Record<string, Json> | undefined;
    entries.push({
      id: operation.operationId,
      method: method.toUpperCase(),
      path,
      area: ((operation.tags as string[] | undefined) ?? [])[0] ?? '',
      summary: operation.summary ?? '',
      detail: firstSentence(operation.description),
      pathParams: parameters.filter((p) => p.in === 'path').map((p) => p.name),
      queryParams: parameters
        .filter((p) => p.in === 'query')
        .map((p) => ({
          name: p.name,
          required: p.required === true,
          type: (p.schema as Json | undefined)?.type ?? 'string',
        })),
      ...(body?.['application/json'] === undefined
        ? {}
        : { body: compact(body['application/json'].schema as Json) }),
    });
  }
}
entries.sort((a, b) => String(a.id).localeCompare(String(b.id)));

writeFileSync(
  new URL('../src/generated/operations.ts', import.meta.url),
  `// Generated by scripts/build-operations.ts from backend/openapi/nix-api.json. Do not edit.\n` +
    `import type { OperationEntry } from '../operations.js';\n\n` +
    `export const OPERATION_ENTRIES: readonly OperationEntry[] = ${JSON.stringify(entries)};\n`,
);
process.stdout.write(`operations: ${String(entries.length)} entries\n`);
